Food foodById(String id) => foods.firstWhere((f) => f.id == id);
Food mealItemFood(MealItem item) => item.snapshot ?? foodById(item.foodId);
Nutrients itemNutrition(MealItem item) =>
    mealItemFood(item).per100g.scaled(item.grams / 100);
Nutrients mealNutrition(Meal meal) => meal.items.fold(
  meal.manual ?? Nutrients.zero,
  (sum, i) => sum + itemNutrition(i),
);
