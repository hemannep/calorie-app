  static String displayNameFor(String code, {bool includeFlag = true}) {
    final name = languageNames[code] ?? code;
    if (!includeFlag) return name;
    final flag = languageFlags[code];
    return flag == null ? name : '$flag $name';
  }

  static AppLocalizations of(BuildContext context) {
    final inherited = Localizations.of<AppLocalizations>(
      context,
      AppLocalizations,
    );
    if (_activeLanguageOverride != null) {
      return AppLocalizations(Locale(_activeLanguageOverride!));
    }
    return inherited ?? const AppLocalizations(Locale('en'));
  }

  static const LocalizationsDelegate<AppLocalizations> delegate =
