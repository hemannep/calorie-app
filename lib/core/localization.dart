  String t(String key) =>
      _translations[locale.languageCode]?[key] ??
      _translations['en']?[key] ??
      key;

  /// Translates legacy display copy while screens migrate to semantic keys.
  /// Exact phrases use the curated catalog; other UI strings are translated
  /// phrase-by-phrase and word-by-word so interpolated values (names,
  /// quantities, dates) survive.
  String translate(String input) {
    final language = locale.languageCode;
    if (language == 'en' || input.trim().isEmpty) return input;
    for (final entry in _translations['en']!.entries) {
      if (entry.value == input) {
        return t(entry.key);
      }
    }
    final phrases = _phraseTranslations[language];
    if (phrases != null) {
      final exact = phrases[input] ?? phrases[input.trim()];
      if (exact != null) return exact;
    }
    if (input.contains('\n')) {
      return input.split('\n').map(translate).join('\n');
    }
    var working = input;
    final subPhrases = _subPhraseTranslations[language];
    if (subPhrases != null) {
      for (final entry in subPhrases.entries) {
        working = working.replaceAll(
          RegExp(RegExp.escape(entry.key), caseSensitive: false),
          entry.value,
        );
      }
    }
    final words = _wordTranslations[language];
    if (words == null) return working;
    return working.replaceAllMapped(RegExp(r"[A-Za-z]+(?:['’][A-Za-z]+)?"), (
      match,
    ) {
      final source = match.group(0)!;
      final normalized = source.toLowerCase().replaceAll('’', "'");
      var translated = words[normalized];
      if (translated == null && normalized.endsWith("'s")) {
        final stem = normalized.substring(0, normalized.length - 2);
        translated = words[stem];
      }
      if (translated == null) return source;
      if (source == source.toUpperCase() && source.length > 1) {
        return translated.toUpperCase();
      }
      return translated;
    });
  }

